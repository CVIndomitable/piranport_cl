"""生成「深渊彼岸花」16x16 方块贴图。

画风对齐 MC 原版花卉（poppy / allium / wither_rose）：
  - 16x16、无抗锯齿硬边缘、整块像素、约 6~9 色
  - 轮廓必须干净：最外一圈统一用最深的 e，亮色只出现在受光面内侧
  - 花瓣之间留 1px 透明缝，靠 alpha 镂空读出分瓣（原版 poppy 同款手法）；
    中缝不能贯穿整个花头，否则会把花劈成左右两半
  - 所有像素必须连通，不能出现"飞出去"的孤立点
  - 石蒜（彼岸花）特征：花瓣细长、向外放射、末端向后翻卷成钩
  - 深渊设定：花瓣近黑，靠"暗紫红→黑"的明度层次塑造体积；
    花蕊用深渊绯红点亮，是全图唯一的暖色锚点
"""
from PIL import Image, ImageDraw

W = H = 16
img = Image.new('RGBA', (W, H), (0, 0, 0, 0))
d = ImageDraw.Draw(img)

# ---- 调色板 ----
# 纯黑在 MC 里会糊成一坨，所以花瓣用"暗紫红→近黑"四档明度拉开层次，
# 花心最亮，整体观感仍是石蒜的黑瓣。
C = {
    'V': (186, 70, 100, 255),  # 花蕊：深渊绯红（全图最亮、唯一暖色）
    'v': (128, 48, 74, 255),   # 花蕊暗部
    'S': (124, 72, 102, 255),  # 花瓣迎光面（只贴花心，不碰轮廓）
    's': (92, 52, 74, 255),    # 花瓣中段
    'm': (62, 33, 49, 255),    # 花瓣主体
    'd': (38, 20, 32, 255),    # 花瓣背光面
    'e': (18, 10, 16, 255),    # 花瓣最外缘/卷钩，收住轮廓
    'G': (74, 143, 40, 255),   # 茎迎光面（沿用原版花茎高光色）
    'g': (58, 116, 36, 255),   # 茎主体
    'h': (37, 84, 30, 255),    # 茎背光面
    'R': (124, 82, 0, 255),    # 海床根盘（沿用原贴图铁锈色，略压暗）
}

# ============================================================
# 花朵：以 (7,7) 为花心，6 枚花瓣向外放射并在末端翻卷。
# 层次由外向内：e 轮廓 → m 主体 → s 中段 → S 迎光 → V 花蕊
# 中缝只在 y=1..5 断开，y=6 之后合拢，避免花头被劈成两半。
# ============================================================
FLOWER = [
    ".......ee.......",   # y=1  顶瓣卷钩
    "......eee.......",   # y=2  顶瓣末端
    "..ee..mm..ee....",   # y=3  左上/右上斜瓣卷钩
    ".eeem.mm.meee...",   # y=4  三瓣主体并行，外侧统一 e 收边
    "..mssmmmsssm....",   # y=5  三瓣根部开始合拢
    "..dSSdVVdSSd....",   # y=6  花蕊点亮，花头合拢
    "...mSSVVSSm.....",   # y=7  花蕊中段，花心亮面展开
    "...dmSSSSmd.....",   # y=8  花蕊下缘
    "....dmddmd......",   # y=9  花冠收口
    ".....mssm.......",   # y=10 花托
    "......Sgm.......",   # y=11 花托与茎衔接
]

for row_i, row in enumerate(FLOWER):
    for col_i, ch in enumerate(row):
        if ch in C:
            d.point((col_i, 1 + row_i), fill=C[ch])

# ============================================================
# 茎：1px 宽，从花托垂直落到底部
# ============================================================
for y in range(11, 16):
    d.point((7, y), fill=C['g'])
d.point((7, 11), fill=C['G'])
d.point((7, 13), fill=C['h'])
d.point((7, 14), fill=C['h'])

# ============================================================
# 根盘：2px 高的海床底座
# ============================================================
for x in range(5, 10):
    d.point((x, 15), fill=C['R'])
for x in (5, 6, 8, 9):
    d.point((x, 14), fill=C['R'])

img.save('/tmp/abysslily/out.png')
print('ok')
